function at(days: number, hours = 0): string {
  return iso(addDays(new Date(), days).getTime() + hours * 60 * 60 * 1000);
}

function buildClient(
  id: string,
  shopName: string,
  ownerName: string,
  city: string,
  phone: string,
  email: string,
  deviceId: string,
  registeredDaysAgo: number,
  trialEndsInDays: number,
  paidUntilDays: number | null,
  blocked = false,
  monthlyPricePkr = DEFAULT_PRICING.defaultMonthlyPricePkr,
): Client {
  return {
    id,
    shopName,
    ownerName,
    city,
    phone,
    email,
    deviceId,
    registeredAt: at(-registeredDaysAgo),
    lastSeenAt: at(0, -2 - Math.floor(Math.random() * 40)),
    plan: paidUntilDays === null ? "trial" : "monthly",
    monthlyPricePkr,
    durationDays: DEFAULT_PRICING.durationDays,
    trialEndsAt: at(trialEndsInDays, trialEndsInDays === 0 ? 20 : 0),
    paidUntil: paidUntilDays === null ? null : at(paidUntilDays),
    blocked,
    notes: "",
  };
}

